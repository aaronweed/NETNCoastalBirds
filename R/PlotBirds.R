
#' @include SumIncubation.R
#' @include SumNestSurveys.R
#' @include SumCreche.R
#'
#'@importFrom rlang .data
#'
#' @title Plot coastal bird survey data
#'
#' @description
#' Plots summarized coastal bird survey data over time. Accepts data frames
#' produced by functions such as \code{\link{SumIncubation}},
#' \code{\link{CrecheSum}}, and \code{\link{SumNestSurveys}}.
#'
#' Data may be plotted as raw counts or effort-adjusted values, with options
#' to filter by species, island, year, life stage, and summary statistic.
#' Time series can be overlaid by life stage, species, or island, and
#' displayed in separate facets.
#'
#' @param df A data frame containing summarized coastal bird survey data.
#'   Typically generated by \code{\link{SumIncubation}},
#'   \code{\link{CrecheSum}}, or \code{\link{SumNestSurveys}}. The data should
#'   contain columns appropriate to the requested plotting options, including
#'   \code{time}, \code{value}, \code{Island}, and \code{variable}.
#'
#' @param raw_count Logical. If \code{TRUE} (default), plot raw counts in \code{value}.
#'   If \code{FALSE} , plot effort-adjusted values in
#'   \code{valuePerSurveySize}.
#'
#' @param species Optional character vector of species codes to include,
#'   such as \code{"BCNH"} or \code{c("DCCO", "HERG")}. Defaults to all
#'   species in \code{df}.
#'
#' @param island Optional character vector of island names to include.
#'   Use \code{"All Islands"} to select records summarized across all islands,
#'   where available. Defaults to all islands represented in \code{df}.
#'
#' @param year Optional numeric or character vector of calendar years to
#'   include. Useful for examining seasonal survey data from selected years.
#'
#' @param stat Optional character vector specifying the summary statistic
#'   to plot, such as \code{"sum"}, \code{"mean"}, \code{"max"}, or
#'   \code{"min"}. Relevant when \code{df} contains multiple statistics.
#'
#' @param scale Character. Specifies the transformation applied to plotted
#'   values. Use \code{"norm"} (default) for untransformed values or
#'   \code{"log"} for natural-log-transformed values.
#'
#' @param facet Character string specifying the data column used to separate
#'   plots into facets. Common choices include \code{"Island"},
#'   \code{"CommonName"}, \code{"Species_Code"}, and \code{"variable"}.
#'   Defaults to \code{"Island"}. Set to \code{NULL} to disable faceting.
#'
#' @param var Optional character vector specifying the survey variable or
#'   life stage to plot, such as \code{"Eggs"}, \code{"Nests"}, or
#'   \code{"Creche size"}. Defaults to all variables.
#'
#' @param overlay Character string specifying the grouping variable for
#'   overlaid time series. Options are:
#'   \describe{
#'     \item{\code{"var"}}{Overlay life stages or survey variables (default).}
#'     \item{\code{"species"}}{Overlay species, using \code{CommonName}.}
#'     \item{\code{"island"}}{Overlay islands, using \code{Island}.}
#'   }
#'
#' @param show_plot Logical. If \code{TRUE} (default), prints the plot.
#'   If \code{FALSE}, return the ggplot object for further modification
#'   or use in other plotting workflows.
#'
#' @param plot_title Logical. If \code{TRUE} (default), add a descriptive
#'   plot title. If \code{FALSE}, omit the title.
#'
#' @param legend Logical. If \code{TRUE}, display the legend above the plot.
#'   Defaults to \code{FALSE}.
#'
#' @param y_scale Character string specifying the facet scale behavior.
#'   Use \code{"fixed"} (default) for a common scale across facets or
#'   \code{"free_y"} to allow each facet to have its own y-axis scale.
#'
#' @return If \code{show_plot = TRUE}, prints a ggplot object. If
#'   \code{show_plot = FALSE}, returns the ggplot object invisibly through
#'   the function's return value.
#'
#' @seealso
#' \code{\link{SumIncubation}},
#' \code{\link{CrecheSum}},
#' \code{\link{SumNestSurveys}},
#' \url{https://www.nps.gov/im/netn/coastal-birds.htm}
#'
#' @examples
#' \dontrun{
#' # Incubation surveys by year
#' dcco <- SumIncubation(time = "year", species = "DCCO", stat = "max")
#' PlotBirds(dcco)
#'
#' # Incubation surveys for multiple species
#' incub <- SumIncubation(
#'   time = "year",
#'   species = c("DCCO", "HERG", "GBBG")
#' )
#' PlotBirds(incub, overlay = "species", stat = "max")
#' PlotBirds(
#'   incub, overlay = "island", stat = "max",
#'   facet = "CommonName", legend = TRUE
#' )
#'
#' # Incubation surveys by date
#' gbbg <- SumIncubation(time = "date", species = "GBBG")
#' PlotBirds(gbbg, year = 2012, legend = TRUE, stat = "sum")
#'
#' # Creche surveys
#' creche <- CrecheSum(time = "date")
#' PlotBirds(creche, year = 2018, stat = "sum")
#' PlotBirds(
#'   creche, year = 2018, island = "All Islands",
#'   facet = "variable", legend = TRUE, stat = "sum"
#' )
#'
#' # Nest surveys
#' nests <- SumNestSurveys(time = "year", species = "BCNH")
#' PlotBirds(nests, var = "Nests")
#' PlotBirds(nests, var = "EggsPerNest", legend = TRUE)
#'
#' # Nest surveys for all species
#' nests <- SumNestSurveys(time = "year")
#' PlotBirds(nests, var = "Nests", overlay = "species")
#' }
#'
#' @export


PlotBirds<-function(df, raw_count= TRUE, species= NULL, island=NULL, year= NULL, stat=NULL,
                    scale= c("norm", "log"), facet= "Island", var= NULL, overlay = "var", show_plot= TRUE, 
                    plot_title = TRUE, legend= FALSE, y_scale ="fixed"){

############################### 
  # Validate arguments
#################################
  
  if (!is.data.frame(df)) {
    stop("'df' must be a data.frame.")
  }
  
  if (!is.logical(raw_count) || length(raw_count) != 1 ||
      is.na(raw_count)) {
    stop("'raw_count' must be TRUE or FALSE.")
  }
  
  if (!is.logical(plot_title) || length(plot_title) != 1 ||
      is.na(plot_title)) {
    stop("'plot_title' must be TRUE or FALSE.")
  }
  
  if (!is.logical(legend) || length(legend) != 1 ||
      is.na(legend)) {
    stop("'legend' must be TRUE or FALSE.")
  }
  
  if (!is.logical(show_plot) || length(show_plot) != 1 ||
      is.na(show_plot)) {
    stop("'show_plot' must be TRUE or FALSE.")
  }
  
  scale <- match.arg(scale, c("norm", "log"))
  overlay <- match.arg(overlay, c("var", "species", "island"))
  y_scale <- match.arg(y_scale, c("fixed", "free_y"))
  
  if (!is.null(facet) && !facet %in% names(df)) {
    stop("The requested facet column is not present in data.")
  }
  
 
  
  ############################### 
  # 2. Check required columns
  ############################### 
  
  required_cols <- c("time", "value", "Island", "variable")
  
  if (!raw_count) {
    required_cols <- c(required_cols, "valuePerSurveySize")
  }
  
  if (overlay == "species") {
    required_cols <- c(required_cols, "CommonName")
  }
  
  if (overlay == "island") {
    required_cols <- c(required_cols, "Island")
  }
  
  missing_cols <- setdiff(required_cols, names(df))
  
  if (length(missing_cols) > 0) {
    stop(
      "Missing required columns: ",
      paste(missing_cols, collapse = ", ")
    )
  }
  
  if (!is.null(facet) &&
      !(length(facet) == 1 && facet %in% names(df))) {
    stop("The requested facet column is not present in data.")
  }
  
  ############################### 
  # subset data
  #################################
  
  graphdata <- df
  
  # check to see if df has "stat" and if stat has been specified
  if("stat" %in% colnames(graphdata) & is.null(stat)){
    cat("WARNING: Please supply argument to stat to avoid incorrectly plotting multiple statistics")
  }
  
  if (!is.null(species)) {
    graphdata <- graphdata[graphdata$Species_Code %in% species, , drop = FALSE ]
  }
  
  if(!is.null(island)){
    graphdata <- graphdata[graphdata$Island %in% island, , drop = FALSE ]
  }
  
  if(!is.null(var)) {
    graphdata<-graphdata[graphdata$variable %in% var, , drop = FALSE]
  }
  
  if(!is.null(year)) {
    graphdata<-graphdata[graphdata$year %in% year, , drop = FALSE] # for subsetting data By Date
  }
  
  if(!is.null(facet) && identical(facet, "Island")) {
    graphdata <- graphdata[
      graphdata$Island != "All Islands" | # remove All islands
      is.na(graphdata$Island), , drop = FALSE] 
  }
  
  # select summary data you want to plot from dataframe with a column "stat" (sum, min, mean, max)

   if ("stat" %in% names(graphdata)) {
    
    if (!is.null(stat)) {
      graphdata <- graphdata[
        graphdata$stat %in% stat, , drop = FALSE
      ]
      
    } else if (length(unique(stats::na.omit(graphdata$stat))) > 1) {
      warning(
        "Multiple statistics are present. Specify 'stat' to select ",
        "the statistic you want to plot."
      )
    }
  }
  
  if (nrow(graphdata) == 0) {
    stop("No observations remain after applying the selected filters.")
  }
  
  ############################### 
  ### SETUP PLOTS 
  ############################### 
  ## what value should be plotted? 
  #The raw counts (value) or effort-adjusted counts (valuePerSurveySize)
  
  if(!raw_count){
    # just rename the vector to grab effort adjusted counts
    graphdata$value<- graphdata$valuePerSurveySize
  }
  
  if (!is.numeric(graphdata$value)) {
    stop("The selected response variable must be numeric.")
  }
  
  if(scale == "log"){ graphdata$value <-log1p(graphdata$value)}
  
  #### overlay control ####
  # overlay by variable (life stage)
  
  color_var <- switch(
    overlay,
    var = "variable",
    species = "CommonName",
    island = "Island"
  )
  
  y2 <- ggplot2::ggplot(
    graphdata,
    ggplot2::aes(
      x = time,
      y = value,
      colour = .data[[color_var]],
      group = .data[[color_var]]
    )
  ) +
    ggplot2::geom_point(size = 2) +
    ggplot2::geom_line() +
    ggplot2::scale_colour_viridis_d(option = "D")
  
  
 
## Setup y-axis labels
  
   if (raw_count) {
    
    y_label <- if (scale == "log") {
      "log(Number Detected) per Survey"
    } else {
      "Number Detected per Survey"
    }
    
  } else {
    
    survey_units <- if ("Survey_Units" %in% names(graphdata)) {
      graphdata$Survey_Units[1]
    } else {
      "Survey Unit"
    }
    
    y_label <- if (scale == "log") {
      paste0("log(Number Detected per ", survey_units, ")")
    } else {
      paste0("Number Detected per ", survey_units)
    }
  }
  
  y2 <- y2 +
    ggplot2::labs(
      x = NULL,
      y = y_label,
      colour = NULL
    )
  
  
### ADD FACETING 
  
  if(!is.null(facet)) {
    y2 <- (y2 + facet_wrap(stats::as.formula(paste("~", facet)), scales = y_scale, ncol = 2 ))
    
  }
#### TOGGLE plot title (above plot) 
  
  if (plot_title) {
    
    species_label <- if (
      "CommonName" %in% names(graphdata) &&
      length(unique(stats::na.omit(graphdata$CommonName))) == 1
    ) {
      unique(stats::na.omit(graphdata$CommonName))[1]
    } else {
      "Coastal bird"
    }
    
    variable_label <- if (is.null(var)) {
      paste(var, collapse = ", ")
    } else {
      NULL
    }
    
    statistic_label <- if (is.null(stat)) {
      paste(stat, collapse = ", ")
    } else {
      NULL
    }
    
    title_text <- paste(
      c(
        if (scale == "log") "Log-transformed",
        statistic_label,
        species_label,
        variable_label,
        "survey data"
      ),
      collapse = " "
    )
    
    y2 <- y2 + ggplot2::ggtitle(title_text)
  }

  # X- axis scaling
  
  if (is.numeric(graphdata$time)) {
    
    time_range <- range(graphdata$time, na.rm = TRUE)
    
    if (all(is.finite(time_range))) {
      y2 <- y2 +
        ggplot2::scale_x_continuous(
          breaks = seq(
            time_range[1],
            time_range[2],
            by = 2
          )
        )
    }
    
  } else if (inherits(graphdata$time, "Date")) {
    
    y2 <- y2 +
      ggplot2::scale_x_date(
        date_minor_breaks = "1 day"
      )
  }
  
  
  ###DEFINE THEME
  y2 <- (y2 +
      ggplot2::theme_bw() +
      ggplot2::theme(
      legend.position = if (legend) "top" else "none",
      legend.key = ggplot2::element_blank(),
      legend.title = ggplot2::element_blank(),
      legend.text = ggplot2::element_text(
        size = 12,
        face = "bold"
      ),
      axis.text.y = ggplot2::element_text(
        color = "black",
        size = 12,
        vjust= 0.5
      ),
      axis.text.x = ggplot2::element_text(
        angle = 0,
        vjust = 0,
        size = 12
      ),
      strip.text = ggplot2::element_text(
        size = 12,
        face = "bold.italic"
      ),
      axis.title = ggplot2::element_text(
        size = 16,
        face = "bold"
      ),
      plot.title = ggplot2::element_text(
        size = 12,
        face = "bold"
      ),
      panel.grid.major = ggplot2::element_line(
        colour = "grey90"
      ),
      strip.background = ggplot2::element_rect(
        fill = "grey95",
        colour = "grey50",
        linewidth = 0.5
      )
    )
  )
  
#### CHOOSE TO PRINT ON EXECUTION OR CREATE OBJECT; THE LATTER HELPFUL WHEN LOOPING  
  
  if(show_plot){
    
    suppressWarnings(print(y2))
    
  }
   return(y2)

}
